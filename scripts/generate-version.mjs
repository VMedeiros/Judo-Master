/**
 * Writes src/environments/version.ts from package.json, so the version shown
 * in the app always matches the released one. Runs before `npm start` and
 * `npm run build`; the output is committed and only changes with the version.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version = '0.0.0' } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const output = `// AUTO-GENERATED by scripts/generate-version.mjs from package.json — do not edit.
export const APP_VERSION = '${version}';
`;

const target = join(root, 'src', 'environments', 'version.ts');
let current = '';
try {
  current = readFileSync(target, 'utf8');
} catch {
  // First run: the file does not exist yet.
}
if (current !== output) writeFileSync(target, output, 'utf8');
console.log(`✅ Version ${version}`);
