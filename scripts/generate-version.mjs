/**
 * Writes the app version from package.json to:
 * - src/environments/version.ts, so the version shown in the app always
 *   matches the released one;
 * - src/version.json, published next to index.html, so a running app can ask
 *   the server which version is out (see AppUpdateService).
 * Runs before `npm start` and `npm run build`; the output is committed and
 * only changes with the version.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version = '0.0.0' } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

/** Writes the file only when its content changes. */
function write(path, output) {
  const target = join(root, ...path);
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // First run: the file does not exist yet.
  }
  if (current !== output) writeFileSync(target, output, 'utf8');
}

write(
  ['src', 'environments', 'version.ts'],
  `// AUTO-GENERATED by scripts/generate-version.mjs from package.json — do not edit.
export const APP_VERSION = '${version}';
`
);
write(['src', 'version.json'], `${JSON.stringify({ version }, null, 2)}\n`);
console.log(`✅ Version ${version}`);
